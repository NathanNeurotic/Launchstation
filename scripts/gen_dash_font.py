#!/usr/bin/env python3
"""Generate src/dash_font_data.c: pre-rasterized dashboard font atlases.

The dashboard uses a proportional anti-aliased typeface instead of the
classic 8x16 bitmap font. Glyphs are rendered here, on the host, with 4x
supersampling into three PSMT8 alpha atlases (small / medium / large em
sizes). At runtime the renderer picks the closest size and scales slightly,
so no font engine is needed on the PS2.

Default face: Roboto Regular (Apache License 2.0). Any TTF/OTF works:

    python scripts/gen_dash_font.py path/to/Roboto-Regular.ttf

Charset: printable ASCII plus Latin-1 (0xA0-0xFF), matching the classic
language files.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

SIZES = [(14, 0.80), (20, 0.88), (32, 1.0)]  # (em px, alpha gamma: <1 thickens)
SS = 4                                      # supersampling factor
ATLAS_W = 256
PAD = 2
FIRST, LAST = 0x20, 0xFF
SKIP = set(range(0x7F, 0xA0))


def render_face(path, em, gamma):
    big = ImageFont.truetype(path, em * SS)
    asc, desc = big.getmetrics()
    ascent = asc / SS
    descent = desc / SS
    xh_box = big.getbbox("x", anchor="ls")
    xheight = -xh_box[1] / SS
    glyphs = {}
    for code in range(FIRST, LAST + 1):
        if code in SKIP:
            continue
        ch = chr(code)
        adv = big.getlength(ch) / SS
        box = big.getbbox(ch, anchor="la")  # relative to top-left of the line (ascender)
        if box is None or box[2] <= box[0] or box[3] <= box[1] or ch == " " or code == 0xA0:
            glyphs[code] = (None, 0, 0, adv)
            continue
        x0, y0, x1, y1 = box
        # align the supersampled crop to SS so downsampling keeps the grid
        ox = (x0 // SS) * SS
        oy = (y0 // SS) * SS
        w = ((x1 - ox + SS - 1) // SS) * SS
        h = ((y1 - oy + SS - 1) // SS) * SS
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-ox, -oy), ch, font=big, fill=255, anchor="la")
        small = img.resize((w // SS, h // SS), Image.BOX)
        if gamma != 1.0:
            small = small.point(lambda v: int(255 * ((v / 255.0) ** gamma) + 0.5))
        glyphs[code] = (small, ox // SS, oy // SS, adv)
    return ascent, descent, xheight, glyphs


def pack(glyphs):
    x = y = PAD
    row_h = 0
    places = {}
    for code in sorted(glyphs):
        img = glyphs[code][0]
        if img is None:
            continue
        w, h = img.size
        if x + w + PAD > ATLAS_W:
            x = PAD
            y += row_h + PAD
            row_h = 0
        places[code] = (x, y)
        x += w + PAD
        row_h = max(row_h, h)
    height = y + row_h + PAD
    height = (height + 7) & ~7
    atlas = Image.new("L", (ATLAS_W, height), 0)
    for code, (px, py) in places.items():
        atlas.paste(glyphs[code][0], (px, py))
    return atlas, places


def c_bytes(data):
    out = []
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    return "\n".join(out)


def main():
    font = sys.argv[1] if len(sys.argv) > 1 else "Roboto-Regular.ttf"
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    parts = [
        "/*",
        " * dash_font_data.c - GENERATED by scripts/gen_dash_font.py, do not edit.",
        " * Face: %s. Roboto is licensed under the Apache License 2.0" % os.path.basename(font),
        " * (http://www.apache.org/licenses/LICENSE-2.0); see docs/dashboard.md.",
        " */",
        '#include "dash_font_data.h"',
        "",
    ]
    faces = []
    for idx, (em, gamma) in enumerate(SIZES):
        ascent, descent, xheight, glyphs = render_face(font, em, gamma)
        atlas, places = pack(glyphs)
        name = "face%d" % idx
        parts.append("static const u8 %s_px[%d] __attribute__((aligned(128))) = {" % (name, atlas.width * atlas.height))
        parts.append(c_bytes(atlas.tobytes()))
        parts.append("};")
        parts.append("static const DashGlyphData %s_glyphs[DASH_FONT_GLYPHS] = {" % name)
        for code in range(FIRST, LAST + 1):
            if code in glyphs:
                img, ox, oy, adv = glyphs[code]
            else:
                img, ox, oy, adv = None, 0, 0, 0.0
            if img is None:
                parts.append("    {0, 0, 0, 0, 0, 0, %d}," % int(round(adv * 16)))
            else:
                px, py = places[code]
                parts.append("    {%d, %d, %d, %d, %d, %d, %d}," % (px, py, img.size[0], img.size[1], ox, oy, int(round(adv * 16))))
        parts.append("};")
        faces.append("    {%d, %d, %d, %d, %d, %d, %s_px, %s_glyphs}," % (
            em, int(round(ascent * 16)), int(round(descent * 16)), int(round(xheight * 16)),
            atlas.width, atlas.height, name, name))
        print("em %d: atlas %dx%d" % (em, atlas.width, atlas.height))
    parts.append("const DashFaceData dash_font_faces[DASH_FONT_FACES] = {")
    parts.extend(faces)
    parts.append("};")
    with open(os.path.join(root, "src", "dash_font_data.c"), "w", newline="\n") as f:
        f.write("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
