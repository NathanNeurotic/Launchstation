"""Generate the optional DS34 ps2build config from the standard definition.

Run from the repository root, then:
    ps2build build -c .ps2-ds34.yaml -o build-ds34
The generated config stays at the root so relative source paths retain meaning.
"""
from pathlib import Path


def configure(source):
    def replace_once(old, new):
        nonlocal source
        if source.count(old) != 1:
            raise ValueError(f"Expected exactly one build anchor: {old!r}")
        source = source.replace(old, new, 1)

    targets = ""
    for transport in ("usb", "bt"):
        name = f"ds34{transport}"
        targets += f"""
  - name: {name}
    type: iop
    sources: [iop/{name}/iop/{name}.c, iop/{name}/iop/smsutils.S]
    include_dirs: [iop/{name}/iop, iop/include_compat]
    imports_lst: iop/{name}/iop/imports.lst
    headers: [usbd, sifcmd, threadman, sysclib, stdio, dmacman, intrman, iomanx, libsd, loadcore, sifman, sysmem, vblank]

  - name: {name}_ee
    type: ee_lib
    sources: [iop/{name}/ee/lib{name}.c]
    include_dirs: [iop/{name}/ee]
    headers: [kernel]
"""
    replace_once("targets:\n", "targets:\n" + targets)
    replace_once("      - src/pad.c\n", "      - src/pad_ds34.c\n")
    replace_once("      - WLE_PS2BUILD\n", "      - DS34\n      - WLE_PS2BUILD\n")
    replace_once("libs: [iopreboot, hdd_ee,", "libs: [ds34usb_ee, ds34bt_ee, iopreboot, hdd_ee,")
    replace_once("      - loader:loader_elf\n", "      - ds34usb\n      - ds34bt\n      - loader:loader_elf\n")
    return "# Generated by scripts/configure_ds34.py; do not edit. DS34 enabled.\n" + source.replace("DS34=0", "DS34=1")


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    output = root / ".ps2-ds34.yaml"
    output.write_text(configure((root / "ps2.yaml").read_text()), encoding="utf-8")
    print(f"Generated {output}")
