# depth of the directory prefix that forms a cohesive group, by top-level directory
GROUP_DEPTH = {"modules": 3, "native": 4, "tests": 2, "tools": 2, "vendor": 4, "third_party": 2,
               ".github": 2, "docs": 2, "iop": 2, "src": 2}

_COMPILED = {r: [(re.compile(p), t, l) for p, t, l in v] for r, v in RULES.items()}


def classify(repo, path, kind):
    """Return (tier, label)."""
    if kind == "binary":
        return "list", "binary file (covered by the asset/clutter inventory, not read as text)"
    if kind.startswith("unreadable"):
        return "list", "unreadable in checkout"
    for rx, tier, label in _COMPILED[repo]:
        if rx.search(path):
            if tier in ("skim", "list"):
                return tier, label
            if tier == "workflow":
                return "buildci", None
            if kind == "doc":
                # prose inside code folders is still documentation
                return ("docs", None) if path.lower().endswith((".md", ".txt", ".html", ".htm", ".rst")) else (tier, None)
            return tier, None
    if kind == "workflow":
        return "buildci", None
    if kind == "doc":
        return "docs", None
    if "/" not in path:
        # root-level build and config files are reviewed together with the workflows
        return "buildci", None
    return "support", None


def group_key(path):
    parts = path.split("/")
    if len(parts) == 1:
        return "(root)"
    depth = GROUP_DEPTH.get(parts[0], 2)
    return "/".join(parts[:min(depth, len(parts) - 1)])
